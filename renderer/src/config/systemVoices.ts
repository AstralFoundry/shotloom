/** 供目录参数当作 optionLabels 使用，让底栏摘要与选择器解析出同一个中文名。 */
export const systemVoiceOptionLabels: Record<string, string> = Object.freeze(
  Object.fromEntries(systemVoices.map((voice) => [voice.value, voice.label])),
);

const labelOf = new Map(systemVoices.map((voice) => [voice.value, voice.label]));
const languageOf = new Map(systemVoices.map((voice) => [voice.value, voice.language]));
const languageLabelOf = new Map(systemVoiceLanguages.map((item) => [item.name, item.label]));

export function systemVoiceLabel(voiceId: unknown): string {
  return labelOf.get(String(voiceId)) || String(voiceId || '');
}

export function systemVoiceLanguageLabel(voiceId: unknown): string {
  const name = languageOf.get(String(voiceId));
  if (!name) return '';
  return languageLabelOf.get(name) || name;
}
